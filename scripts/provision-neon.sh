#!/usr/bin/env bash
# One-shot Neon setup for Sila:
#   - Creates sila_owner + sila_app (if not present)
#   - Sets FRESH random passwords on both
#   - Hands ownership of the database + public schema to sila_owner
#   - Runs the drizzle migrations as sila_owner
#   - Applies scripts/sql/grant-app.sql
#   - Writes .env.render   (gitignored, chmod 600): the exact set of env
#     vars the Render service reads at runtime (DATABASE_URL is sila_app).
#   - Writes .env.github   (gitignored, chmod 600): DATABASE_ADMIN_URL only,
#     to paste into the DATABASE_ADMIN_URL GitHub secret.
#
# Reads NEON_OWNER_URL from the repo's .env (which is gitignored). Never
# prints any secret to stdout or to any file outside the two above.
#
# Idempotent on re-run. Safe to run again if a step fails midway.

set -eu
cd "$(dirname "$0")/.."

ENV_FILE=".env"
if [ ! -f "$ENV_FILE" ]; then
  echo "[provision] $ENV_FILE not found; put NEON_OWNER_URL in it first" >&2
  exit 2
fi

# shellcheck disable=SC1090
set -a; . "$ENV_FILE"; set +a

if [ -z "${NEON_OWNER_URL:-}" ]; then
  echo "[provision] NEON_OWNER_URL is empty or unset" >&2
  exit 2
fi

for cmd in psql node npx openssl; do
  if ! command -v "$cmd" >/dev/null 2>&1; then
    echo "[provision] missing command: $cmd" >&2
    exit 3
  fi
done

gen() {
  # 32 bytes of randomness → base64url (no =, no /, no +). 43 chars.
  node -e "console.log(require('crypto').randomBytes(${1:-32}).toString('base64url'))"
}

SILA_OWNER_PW="$(gen 32)"
SILA_APP_PW="$(gen 32)"
SILA_KEK="$(gen 32)"
SESSION_SECRET="$(gen 32)"
VOLUNTEER_HMAC_KEY="$(gen 32)"
DEMO_PASSWORD="$(gen 24)"
EVALUATOR_PASSWORD="$(gen 24)"

echo "[provision] creating roles sila_owner + sila_app (idempotent)"
psql "$NEON_OWNER_URL" -v ON_ERROR_STOP=1 -q -f scripts/sql/setup-roles.sql

echo "[provision] setting fresh passwords on both roles"
psql "$NEON_OWNER_URL" -v ON_ERROR_STOP=1 -q \
  -c "ALTER ROLE sila_owner WITH LOGIN PASSWORD '$SILA_OWNER_PW';" \
  -c "ALTER ROLE sila_app   WITH LOGIN PASSWORD '$SILA_APP_PW';"

# Figure out the host + database from the owner URL (host is the SNI + port,
# database is the path). Query parameters on the owner URL (sslmode, channel
# binding, project id) are preserved so Neon's direct endpoint accepts us.
PARSE_URL_JS='
const u = new URL(process.env.NEON_OWNER_URL);
const host = u.host; // keeps port if present
const db = (u.pathname || "/").slice(1) || "neondb";
const search = u.search || "?sslmode=require";
process.stdout.write(JSON.stringify({host, db, search}));
'
PARSED=$(NEON_OWNER_URL="$NEON_OWNER_URL" node -e "$PARSE_URL_JS")
HOST=$(node -e "console.log(JSON.parse(process.argv[1]).host)" "$PARSED")
DB=$(node -e "console.log(JSON.parse(process.argv[1]).db)" "$PARSED")
QS=$(node -e "console.log(JSON.parse(process.argv[1]).search)" "$PARSED")

echo "[provision] host=$HOST database=$DB"

DATABASE_ADMIN_URL="postgres://sila_owner:${SILA_OWNER_PW}@${HOST}/${DB}${QS}"
DATABASE_URL="postgres://sila_app:${SILA_APP_PW}@${HOST}/${DB}${QS}"

echo "[provision] handing ownership of the schema + database to sila_owner"
psql "$NEON_OWNER_URL" -v ON_ERROR_STOP=1 -q \
  -c "ALTER DATABASE \"$DB\" OWNER TO sila_owner;" \
  -c "ALTER SCHEMA  public  OWNER TO sila_owner;"

echo "[provision] applying migrations as sila_owner"
DATABASE_ADMIN_URL="$DATABASE_ADMIN_URL" npx tsx scripts/db-migrate.ts

echo "[provision] applying sila_app grants"
psql "$DATABASE_ADMIN_URL" -v ON_ERROR_STOP=1 -q -f scripts/sql/grant-app.sql

echo "[provision] verifying sila_app can connect and has the expected privilege"
psql "$DATABASE_URL" -v ON_ERROR_STOP=1 -At -q -c "select current_user, current_database();"

umask 077
cat > .env.render <<EOF
# Generated by scripts/provision-neon.sh — DO NOT COMMIT.
# Load these into the Render service's environment (Dashboard → Environment).
DATABASE_URL=$DATABASE_URL
SILA_KEK=$SILA_KEK
SESSION_SECRET=$SESSION_SECRET
VOLUNTEER_HMAC_KEY=$VOLUNTEER_HMAC_KEY
DEMO_PASSWORD=$DEMO_PASSWORD
EVALUATOR_PASSWORD=$EVALUATOR_PASSWORD
DEMO_MODE=true
NODE_ENV=production
EOF
chmod 600 .env.render

cat > .env.github <<EOF
# Generated by scripts/provision-neon.sh — DO NOT COMMIT.
# Paste this value into the GitHub repo secret named DATABASE_ADMIN_URL
# (Settings → Secrets and variables → Actions → New repository secret).
DATABASE_ADMIN_URL=$DATABASE_ADMIN_URL
EOF
chmod 600 .env.github

cat <<'MSG'

[provision] done.

Next steps (nothing printed to stdout is a secret):
  1. Open .env.render — copy the KEY=VALUE pairs into Render's Environment tab.
     IMPORTANT: copy SILA_KEK into your password manager too. If SILA_KEK is lost,
     every vault becomes unreadable.
  2. Open .env.github — paste DATABASE_ADMIN_URL into the GitHub repo secret of
     the same name. Only the deploy + backup workflows read it.
  3. Keep both files on disk (gitignored by .env*) until you have confirmed the
     live site works. They can be deleted after v1.0.0-pilot is tagged.
MSG
